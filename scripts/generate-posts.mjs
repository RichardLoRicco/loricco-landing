/*
  Compiles content/posts/authored/*.md into content/posts/authored.generated.ts.
  Adapted from the LoRicco Law site's generator: Markdown in, a typed, sanitized
  module out, and a loud failure on anything the post template cannot render.

  `node scripts/generate-posts.mjs`           write the module
  `node scripts/generate-posts.mjs --check`   fail if the module is stale
*/
import fs from "node:fs/promises";
import path from "node:path";
import matter from "gray-matter";
import { unified } from "unified";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import rehypeSanitize from "rehype-sanitize";
import rehypeStringify from "rehype-stringify";
import { visit } from "unist-util-visit";

const root = process.cwd();
const authoredDir = path.join(root, "content", "posts", "authored");
const generatedPath = path.join(root, "content", "posts", "authored.generated.ts");

const RESERVED_SLUGS = new Set(["feed.xml", "page"]);

const htmlSchema = {
  clobberPrefix: "post-",
  tagNames: ["a", "blockquote", "br", "code", "em", "h2", "h3", "li", "ol", "p", "strong", "ul"],
  attributes: { a: ["href", "title"] },
  protocols: { href: ["http", "https", "mailto", "tel"] },
};

const supportedNodes = new Set([
  "blockquote", "break", "emphasis", "heading", "inlineCode", "link", "list",
  "listItem", "paragraph", "root", "strong", "text",
]);

// Heuristics, not limits: search engines show roughly this much before
// truncating. Warn and never truncate reviewed copy.
const TITLE_HEURISTIC = 60;
const DESCRIPTION_HEURISTIC = 160;

// The post template renders the general-information line on every post, so a
// body that repeats it would show it twice.
const DISCLAIMER_FRAGMENT = /general information,? not legal advice/i;

const checkMode = process.argv.includes("--check");
const warnings = [];

const files = (await fs.readdir(authoredDir)).filter((f) => f.endsWith(".md")).sort();
const posts = [];
const seenSlugs = new Set();

for (const file of files) {
  const source = await fs.readFile(path.join(authoredDir, file), "utf8");
  const { data: fm, content } = matter(source);

  const slug = expectString(fm.slug, file, "slug");
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    throw new Error(`${file}: slug must be lowercase words joined by single hyphens`);
  }
  if (RESERVED_SLUGS.has(slug)) throw new Error(`${file}: slug "${slug}" is reserved`);
  if (seenSlugs.has(slug)) throw new Error(`${file}: duplicate slug "${slug}"`);
  seenSlugs.add(slug);

  const publishedAt = expectDate(fm.publishedAt, file, "publishedAt");
  const updatedAt = optionalDate(fm.updatedAt, file, "updatedAt");
  if (updatedAt !== undefined && updatedAt < publishedAt) {
    throw new Error(`${file}: updatedAt (${updatedAt}) precedes publishedAt (${publishedAt})`);
  }

  if (DISCLAIMER_FRAGMENT.test(content)) {
    throw new Error(`${file}: the body repeats the general-information line the template already renders`);
  }

  const bodyHtml = await markdownToHtml(content, file);
  const faqs = await compileFaqs(fm.faqs ?? [], file);

  const post = {
    slug,
    title: expectString(fm.title, file, "title"),
    description: expectString(fm.description, file, "description"),
    metaTitle: expectString(fm.metaTitle, file, "metaTitle"),
    metaDescription: expectString(fm.metaDescription, file, "metaDescription"),
    publishedAt,
    updatedAt,
    series: optionalString(fm.series, file, "series"),
    tags: expectStringArray(fm.tags, file, "tags"),
    videoUrl: optionalUrl(fm.videoUrl, file, "videoUrl"),
    wordCount: countWords(content),
    bodyHtml,
    faqs: faqs.length ? faqs : undefined,
  };

  for (const field of ["metaTitle", "metaDescription", "title", "description"]) {
    // Dash punctuation is a house rule for search-facing copy (hyphens inside
    // compound words are fine).
    if (/\s[–—-]\s|[–—]/.test(post[field])) {
      throw new Error(`${file}: ${field} uses dash punctuation`);
    }
  }
  if (post.metaTitle.length > TITLE_HEURISTIC) {
    warnings.push(`${file}: metaTitle is ${post.metaTitle.length} chars (heuristic ${TITLE_HEURISTIC})`);
  }
  if (post.metaDescription.length > DESCRIPTION_HEURISTIC) {
    warnings.push(`${file}: metaDescription is ${post.metaDescription.length} chars (heuristic ${DESCRIPTION_HEURISTIC})`);
  }

  posts.push(stripUndefined(post));
}

posts.sort((a, b) => {
  const byDate = b.publishedAt.localeCompare(a.publishedAt);
  return byDate !== 0 ? byDate : a.slug.localeCompare(b.slug);
});

for (const w of warnings) console.warn(w);

const generated = `import type { Post } from "./schema";

// Generated by scripts/generate-posts.mjs from content/posts/authored/*.md. Do not hand-edit.
export const authoredPosts: readonly Post[] = ${JSON.stringify(posts, null, 2)};
`;

if (checkMode) {
  const existing = await fs.readFile(generatedPath, "utf8").catch(() => "");
  if (existing !== generated) {
    console.error("Generated post data is stale. Run `npm run generate:posts` and commit the result.");
    process.exit(1);
  }
  console.log(`Generated post data is up to date for ${posts.length} posts.`);
} else {
  await fs.writeFile(generatedPath, generated);
  console.log(`Generated ${posts.length} posts.`);
}

async function compileFaqs(faqs, file) {
  if (!Array.isArray(faqs)) throw new Error(`${file}: faqs must be a list`);
  const out = [];
  for (const [i, faq] of faqs.entries()) {
    const label = `${file}: faqs[${i}]`;
    const question = expectString(faq?.question, label, "question");
    const markdown = expectString(faq?.answer, label, "answer");
    const html = inlineFromSingleParagraph(await markdownToHtml(markdown, label));
    const rich = /[[*_`<>]/.test(markdown);
    out.push(stripUndefined({ question, answer: plainText(html), answerHtml: rich ? html : undefined }));
  }
  return out;
}

async function markdownToHtml(markdown, label) {
  const processor = unified()
    .use(remarkParse)
    .use(validateMarkdown(label))
    .use(remarkRehype)
    .use(rehypeSanitize, htmlSchema)
    .use(rehypeStringify);
  return String(await processor.process(markdown)).trim();
}

function validateMarkdown(label) {
  return () => (tree) => {
    visit(tree, (node) => {
      if (!supportedNodes.has(node.type)) {
        throw new Error(`${label}: unsupported Markdown node "${node.type}"`);
      }
      if (node.type === "heading" && node.depth !== 2 && node.depth !== 3) {
        throw new Error(`${label}: only ## and ### headings are supported`);
      }
      if (node.type === "link") validateHref(node.url, label);
    });
  };
}

function validateHref(href, label) {
  if (typeof href !== "string" || href.length === 0) throw new Error(`${label}: empty link href`);
  if (href.startsWith("/")) {
    if (href.startsWith("//")) throw new Error(`${label}: protocol-relative links are not supported`);
    const pathPart = href.split(/[?#]/)[0];
    // This site does not use trailing slashes (next.config.ts default).
    if (pathPart !== "/" && pathPart.endsWith("/")) {
      throw new Error(`${label}: internal links must not end with a slash: ${href}`);
    }
    return;
  }
  if (!/^https?:\/\//i.test(href) && !/^(?:mailto|tel):/i.test(href)) {
    throw new Error(`${label}: external links must use http, https, mailto, or tel: ${href}`);
  }
}

function countWords(markdown) {
  return markdown
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[#>*_`]/g, " ")
    .split(/\s+/)
    .filter(Boolean).length;
}

function expectString(v, file, field) {
  if (typeof v !== "string" || v.trim().length === 0) throw new Error(`${file}: ${field} must be a non-empty string`);
  return v;
}
function optionalString(v, file, field) {
  return v === undefined ? undefined : expectString(v, file, field);
}
function optionalUrl(v, file, field) {
  if (v === undefined) return undefined;
  const s = expectString(v, file, field);
  if (!/^https:\/\//.test(s)) throw new Error(`${file}: ${field} must be an https URL`);
  return s;
}
function expectStringArray(v, file, field) {
  if (!Array.isArray(v) || v.length === 0) throw new Error(`${file}: ${field} must be a non-empty list`);
  return v.map((item, i) => expectString(item, file, `${field}[${i}]`));
}
function expectDate(v, file, field) {
  const s = v instanceof Date ? v.toISOString().slice(0, 10) : v;
  if (typeof s !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(s)) throw new Error(`${file}: ${field} must be YYYY-MM-DD`);
  return s;
}
function optionalDate(v, file, field) {
  return v === undefined ? undefined : expectDate(v, file, field);
}
function stripUndefined(obj) {
  return Object.fromEntries(Object.entries(obj).filter(([, v]) => v !== undefined));
}
function inlineFromSingleParagraph(html) {
  if (!html.startsWith("<p>") || !html.endsWith("</p>")) return html;
  const inner = html.slice(3, -4);
  return inner.includes("</p>") ? html : inner;
}
function plainText(html) {
  return decode(
    html
      .replace(/<br\s*\/?>/gi, " ")
      .replace(/<\/?(?:p|li|ul|ol|h2|h3|blockquote)[^>]*>/gi, " ")
      .replace(/<[^>]*>/g, ""),
  )
    .replace(/\s+/g, " ")
    .trim();
}
function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#([0-9]+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ");
}
